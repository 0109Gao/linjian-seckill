const { chromium } = require('playwright-core')
const ACT2 = '2116127895213543425'
;(async () => {
  const b = await chromium.launch({ channel: 'msedge', headless: true })
  const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 }, deviceScaleFactor: 2 })
  const a = await fetch('http://localhost/api/auth/login', { method:'POST', headers:{'Content-Type':'application/json'}, body: JSON.stringify({username:'admin',password:'123456'}) }).then(r=>r.json())
  await ctx.addInitScript(([t,r])=>{localStorage.setItem('accessToken',t);localStorage.setItem('refreshToken',r)}, [a.data.accessToken, a.data.refreshToken])
  const p = await ctx.newPage()
  const errs = []
  p.on('console', m => { if (m.type()==='error') errs.push(m.text().slice(0,100)) })
  await p.goto(`http://localhost/admin/stock?activityId=${ACT2}`, { waitUntil:'domcontentloaded' })
  await p.waitForTimeout(3000)
  const sel = await p.locator('.el-select__selected-item, .el-select__placeholder').first().textContent().catch(()=>'(读取失败)')
  const rows = await p.locator('.el-table__body tr').count()
  const firstRow = await p.locator('.el-table__body tr').first().innerText().catch(()=>'')
  const alerts = await p.locator('.el-message').allTextContents().catch(()=>[])
  console.log('下拉显示:', (sel||'').trim())
  console.log('表格行数:', rows)
  console.log('首行内容:', firstRow.replace(/\s+/g,' ').slice(0,120))
  console.log('弹窗提示:', JSON.stringify(alerts))
  console.log('控制台错误:', errs.length ? errs : '(无)')
  await p.screenshot({ path: 'D:/WorkBuddy/项目/linjian-seckill/docs/screenshots/11-admin-stock.png', fullPage: true, animations: 'disabled' })
  console.log('截图已更新')
  await b.close()
})()
