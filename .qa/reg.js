const { chromium } = require('playwright-core')
;(async () => {
  const b = await chromium.launch({ channel: 'msedge', headless: true })
  const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
  await p.goto('http://localhost/user/login')
  await p.waitForLoadState('networkidle'); await p.waitForTimeout(800)

  await p.locator('#tab-register').click()
  await p.waitForTimeout(700)
  const name = 'uiauto' + Date.now().toString().slice(-6)
  await p.locator('input[placeholder^="用户名（4~32"]').fill(name)
  await p.locator('input[placeholder^="昵称"]').fill('自动化注册')
  await p.locator('input[placeholder^="密码（6~64"]').fill('123456')
  await p.locator('input[placeholder="确认密码"]').fill('123456')
  await p.locator('button:has-text("注册并登录")').click()
  await p.waitForTimeout(3000)
  console.log('注册账号:', name)
  console.log('提交后 URL:', p.url())
  console.log('localStorage token:', !!(await p.evaluate(() => localStorage.getItem('accessToken'))))
  console.log('顶部是否显示用户名:', (await p.locator('.topbar .user').count()) > 0)

  // 重复注册应报错
  await p.goto('http://localhost/user/login')
  await p.waitForTimeout(600)
  await p.locator('#tab-register').click()
  await p.waitForTimeout(500)
  await p.locator('input[placeholder^="用户名（4~32"]').fill(name)
  await p.locator('input[placeholder^="密码（6~64"]').fill('123456')
  await p.locator('input[placeholder="确认密码"]').fill('123456')
  await p.locator('button:has-text("注册并登录")').click()
  await p.waitForTimeout(2000)
  const msg = await p.locator('.el-message, .el-form-item__error').allTextContents().catch(()=>[])
  console.log('重复注册提示:', JSON.stringify(msg.map(m=>m.trim())))
  await b.close()
})()
